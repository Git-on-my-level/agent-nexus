package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// contractEnum is one schema enum in contract order. Order is part of the
// contract for ordered enums such as board_column_key, so it is never sorted.
type contractEnum struct {
	Name    string            `json:"name"`
	Policy  string            `json:"enum_policy"`
	Values  []string          `json:"values"`
	Aliases map[string]string `json:"aliases,omitempty"`
}

func collectContractEnums(schemaDoc anxSchemaDocument) ([]contractEnum, error) {
	names := make([]string, 0, len(schemaDoc.Enums))
	for name := range schemaDoc.Enums {
		names = append(names, name)
	}
	sort.Strings(names)
	out := make([]contractEnum, 0, len(names))
	identifiers := map[string]string{}
	for _, name := range names {
		def := schemaDoc.Enums[name]
		values := compactStrings(def.Values)
		if len(values) == 0 {
			continue
		}
		seen := map[string]struct{}{}
		for _, value := range values {
			if _, dup := seen[value]; dup {
				return nil, fmt.Errorf("enum %s lists %q twice", name, value)
			}
			seen[value] = struct{}{}
			ident := toPascalCase(name) + toPascalCase(value)
			if prior, clash := identifiers[ident]; clash {
				return nil, fmt.Errorf("enum constant %s is generated by both %s and %s.%s", ident, prior, name, value)
			}
			identifiers[ident] = name + "." + value
		}
		var aliases map[string]string
		for alias, target := range def.Aliases {
			alias = strings.TrimSpace(alias)
			target = strings.TrimSpace(target)
			if _, ok := seen[target]; !ok {
				return nil, fmt.Errorf("enum %s alias %q targets unknown value %q", name, alias, target)
			}
			if _, ok := seen[alias]; ok {
				return nil, fmt.Errorf("enum %s alias %q shadows a canonical value", name, alias)
			}
			if aliases == nil {
				aliases = map[string]string{}
			}
			aliases[alias] = target
		}
		out = append(out, contractEnum{Name: name, Policy: strings.TrimSpace(def.EnumPolicy), Values: values, Aliases: aliases})
	}
	return out, nil
}

func sortedAliasKeys(aliases map[string]string) []string {
	keys := make([]string, 0, len(aliases))
	for key := range aliases {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func writeContractEnumsJSON(enums []contractEnum) error {
	b, err := json.MarshalIndent(enums, "", "  ")
	if err != nil {
		return err
	}
	_, err = os.Stdout.Write(append(b, '\n'))
	return err
}

func writeGoEnums(goOutDir string, enums []contractEnum) error {
	dir := filepath.Join(goOutDir, "enums")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by contract-gen from contracts/anx-schema.yaml. DO NOT EDIT.\n\n")
	b.WriteString("// Package enums holds the shared schema enums in contract order. Import these\n")
	b.WriteString("// instead of writing value lists by hand; scripts/check-enum-conformance.mjs\n")
	b.WriteString("// rejects hand-written copies.\n")
	b.WriteString("package enums\n\n")
	b.WriteString("import \"strings\"\n\n")
	for _, enum := range enums {
		typeName := toPascalCase(enum.Name)
		b.WriteString("// " + enum.Name + " values (" + enum.Policy + "), in contract order.\n")
		b.WriteString("const (\n")
		for _, value := range enum.Values {
			fmt.Fprintf(&b, "\t%s%s = %s\n", typeName, toPascalCase(value), strconv.Quote(value))
		}
		b.WriteString(")\n\n")
		fmt.Fprintf(&b, "// %sValues lists every %s value in contract order. Do not modify it.\n", typeName, enum.Name)
		fmt.Fprintf(&b, "var %sValues = []string{", typeName)
		for i, value := range enum.Values {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(typeName + toPascalCase(value))
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "// Is%s reports whether value is exactly a canonical %s value.\n", typeName, enum.Name)
		fmt.Fprintf(&b, "func Is%s(value string) bool {\n\tswitch value {\n\tcase ", typeName)
		for i, value := range enum.Values {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(typeName + toPascalCase(value))
		}
		b.WriteString(":\n\t\treturn true\n\t}\n\treturn false\n}\n\n")
		if len(enum.Aliases) == 0 {
			continue
		}
		fmt.Fprintf(&b, "// %sAliases maps accepted legacy spellings to their canonical %s value.\n", typeName, enum.Name)
		fmt.Fprintf(&b, "var %sAliases = map[string]string{\n", typeName)
		for _, alias := range sortedAliasKeys(enum.Aliases) {
			fmt.Fprintf(&b, "\t%s: %s%s,\n", strconv.Quote(alias), typeName, toPascalCase(enum.Aliases[alias]))
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "// Normalize%s trims and lower-cases value, then folds an alias to its\n", typeName)
		fmt.Fprintf(&b, "// canonical %s value. ok is false when value is neither.\n", enum.Name)
		fmt.Fprintf(&b, "func Normalize%s(value string) (canonical string, ok bool) {\n", typeName)
		b.WriteString("\tvalue = strings.ToLower(strings.TrimSpace(value))\n")
		fmt.Fprintf(&b, "\tif Is%s(value) {\n\t\treturn value, true\n\t}\n", typeName)
		fmt.Fprintf(&b, "\tcanonical, ok = %sAliases[value]\n\treturn canonical, ok\n}\n\n", typeName)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format generated enums: %w", err)
	}
	return os.WriteFile(filepath.Join(dir, "enums_gen.go"), src, 0o644)
}

func tsConstName(value string) string {
	return strings.ToUpper(toSnakeIdentifier(value))
}

func toSnakeIdentifier(value string) string {
	var b strings.Builder
	for _, r := range value {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteRune('_')
		}
	}
	return b.String()
}

func writeTSEnums(tsOutDir string, enums []contractEnum) error {
	if err := os.MkdirAll(tsOutDir, 0o755); err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("// Code generated by contract-gen from contracts/anx-schema.yaml. DO NOT EDIT.\n")
	b.WriteString("// Shared schema enums in contract order. Import these instead of writing value\n")
	b.WriteString("// lists by hand; scripts/check-enum-conformance.mjs rejects hand-written copies.\n\n")
	for _, enum := range enums {
		name := tsConstName(enum.Name)
		quoted := make([]string, 0, len(enum.Values))
		for _, value := range enum.Values {
			quoted = append(quoted, strconv.Quote(value))
		}
		fmt.Fprintf(&b, "/** %s values (%s), in contract order. */\n", enum.Name, enum.Policy)
		fmt.Fprintf(&b, "export const %s_VALUES: readonly string[] = Object.freeze([%s]);\n\n", name, strings.Join(quoted, ", "))
		if len(enum.Aliases) == 0 {
			continue
		}
		fmt.Fprintf(&b, "/** Accepted legacy %s spellings and the canonical value each folds to. */\n", enum.Name)
		fmt.Fprintf(&b, "export const %s_ALIASES: Readonly<Record<string, string>> = Object.freeze({\n", name)
		for _, alias := range sortedAliasKeys(enum.Aliases) {
			fmt.Fprintf(&b, "  %s: %s,\n", strconv.Quote(alias), strconv.Quote(enum.Aliases[alias]))
		}
		b.WriteString("});\n\n")
		fmt.Fprintf(&b, "/** Trim and lower-case value, then fold an alias; \"\" when it is neither a %s value nor an alias. */\n", enum.Name)
		fmt.Fprintf(&b, "export function normalize%s(value: unknown): string {\n", toPascalCase(enum.Name))
		b.WriteString("  const text = String(value ?? \"\").trim().toLowerCase();\n")
		fmt.Fprintf(&b, "  if (%s_VALUES.includes(text)) return text;\n", name)
		fmt.Fprintf(&b, "  return Object.prototype.hasOwnProperty.call(%s_ALIASES, text) ? %s_ALIASES[text] : \"\";\n}\n\n", name, name)
	}
	return os.WriteFile(filepath.Join(tsOutDir, "enums.ts"), []byte(strings.TrimRight(b.String(), "\n")+"\n"), 0o644)
}
